# Часть 2
# Исходные данные
def y(x):
    return x ** 0.5 / (1 + 2 * x) ** 2
x0 = 1.0
x1 = 5.0
h1 = 1
h2 = 0.5

# МП h1
F1 = sum([h1 * y(x0 + h1 / 2 + i * h1) for i in range (int((x1 - x0) / h1))])
print('МП с шагом h1: F =', F1)

# МП h2
F2 = sum([h2 * y(x0 + h2 / 2 + i * h2) for i in range (int((x1 - x0) / h2))])
print ('МП с шагом h2: F =', F2)

# Уточнение МП методом Рунге-Ромберга-Ричардсона
F3 = F1 + (F1-F2) / ((h2 / h1) ** 2 - 1)
print ('Уточнение МП методом Рунге-Ромберга-Ричардсона: F =', F3)

# МТ h1
F4 = 0.5 * sum([h1 * (y(x0 + i * h1) + y(x0 + i * h1 + h1)) for i in range (int((x1 - x0) / h1))])
print ('МТ с шагом h1: F =', F4)

# МТ h2
F5 = 0.5 * sum([h2 * (y(x0 + i * h2) + y(x0 + i * h2 + h2)) for i in range (int((x1 - x0) / h2))])
print ('МТ с шагом h2: F =', F5)

# Уточнение МТ методом Рунге-Ромберга-Ричардсона
F6 = F4 + (F4-F5) / ((h2 / h1) ** 2 - 1)
print ('Уточнение МТ методом Рунге-Ромберга-Ричардсона: F =', F6)

# МС h1
F7 = h1 / 3 * sum([y(x0 + i * h1) + 4 * y(x0 + (i + 1) * h1) + y(x0 + (i + 2) * h1)
                  for i in range (0, int((x1 - x0) / h1), 2)])
F8 = h2 / 3 * sum([y(x0 + i * h2) + 4 * y(x0 + (i + 1) * h2) + y(x0 + (i + 2) * h2)
                  for i in range (0, int((x1 - x0) / h2), 2)])
print ('МС с шагом h2: F =', F8)

# Уточнение МС методом Рунге-Ромберга-Ричардсона
F9 = F7 + (F7-F8) / ((h2 / h1) ** 4 - 1)
print ('Уточнение МС методом Рунге-Ромберга-Ричардсона: F =', F9)